export function getKarmaAlignment(karma: number): {
  label: string;
  tier: 'alvor' | 'vigilia' | 'eclipse';
  col: string;
  desc: string;
} {
  if (karma >= 25) {
    return {
      label: 'Alvor Purificado',
      tier: 'alvor',
      col: '#f6d27a',
      desc: 'Compaixão e vigília luminosa rumo ao amanhecer.',
    };
  }
  if (karma <= -25) {
    return {
      label: 'Abismo Carmesim',
      tier: 'eclipse',
      col: '#d94854',
      desc: 'Fome de sangue e pactos profanos sob a lua vermelha.',
    };
  }
  return {
    label: 'Crepúsculo Equilibrado',
    tier: 'vigilia',
    col: '#9ed7f0',
    desc: 'Entre a luz e a sombra, guardião silencioso da névoa.',
  };
}

